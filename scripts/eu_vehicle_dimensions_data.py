def _fallback_dims(brand: str, model: str) -> tuple[float, float, float]:
    """Ultimo ricorso: stima conservativa da parole chiave nel nome."""
    m = model.lower()
    if any(k in m for k in ("berlingo", "proace", "tourneo", "doblo", "transit")):
        return 4.75, 1.90, 1.90
    if any(k in m for k in ("navara", "hilux", "r1t")):
        return 5.35, 1.90, 1.85
    if "bus" in m or "buzz" in m:
        return 4.71, 1.99, 1.94
    if "mpv" in m or "zafira" in m or "galaxy" in m or "s-max" in m:
        return 4.75, 1.88, 1.68
    if any(k in m for k in ("suv", "x-trail", "sportage", "tucson", "kuga")):
        return 4.52, 1.86, 1.65
    if any(k in m for k in ("grand cherokee", "defender", "land cruiser")):
        return 4.95, 1.95, 1.85
    # media berlina / crossover generico
    return 4.35, 1.82, 1.55


def _adjust_year(brand: str, model: str, year: int, l: float, w: float, h: float) -> tuple[float, float, float]:
    """Regole generazione / facelift (solo dove cambia in modo rilevante)."""
    if brand == "Peugeot" and model == "208":
        if year >= 2019:
            return 4.05, 1.75, 1.43
        return 3.96, 1.74, 1.46
    if brand == "Peugeot" and model == "207" and year >= 2009:
        return 4.03, 1.73, 1.47
    if brand == "Volkswagen" and model == "Golf":
        if year >= 2020:
            return 4.29, 1.79, 1.49
        if year >= 2013:
            return 4.26, 1.79, 1.49
        return 4.22, 1.76, 1.48
    if brand == "Renault" and model == "Clio":
        if year >= 2019:
            return 4.05, 1.74, 1.44
        if year >= 2013:
            return 4.06, 1.73, 1.45
        return 4.03, 1.72, 1.50
    if brand == "Ford" and model == "Fiesta":
        if year >= 2018:
            return 4.04, 1.74, 1.48
        return 3.97, 1.72, 1.46
    return l, w, h


def resolve_dims(brand: str, model: str, year: int) -> tuple[float, float, float]:
    base = MODEL_DIMS.get((brand, model)) or _fallback_dims(brand, model)
    l, w, h = _adjust_year(brand, model, year, *base)
    # Variazione annuale leggera (facelift ~ pochi cm su generazioni lunghe), non cumulativa aggressiva
    yref = 2018
    delta = max(-0.02, min(0.02, (year - yref) * 0.0008))
    return round(l + delta, 2), round(w + delta * 0.6, 2), round(h + delta * 0.4, 2)


def length_segment_for_economics(length_m: float) -> str:
    """Segmento per consumi/manutenzione in base alla lunghezza reale."""
    if length_m < 3.78:
        return "small"
    if length_m < 4.22:
        return "compact"
    if length_m < 4.65:
        return "medium"
    return "suv"
